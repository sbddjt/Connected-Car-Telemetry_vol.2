"use strict";
const assert = require("node:assert/strict");
const { distanceMeters, interpolateCoordinate, shouldAnimateLocation, latestObservationAge } = require("../frontend/map_motion.js");
const previous = {run_id:"one",event_time:"2026-10-06T00:00:00Z",value:{latitude:37.497,longitude:127.03}};
const next = {...previous,event_time:"2026-10-06T00:00:01Z",value:{latitude:37.4971,longitude:127.03}};
assert.ok(distanceMeters([37.497,127.03],[37.4971,127.03]) > 11);
assert.ok(distanceMeters([37.497,127.03],[37.4971,127.03]) < 12);
assert.equal(shouldAnimateLocation(previous,next),true);
assert.equal(shouldAnimateLocation(previous,next,true),false);
assert.equal(shouldAnimateLocation(previous,{...next,run_id:"two"}),false);
assert.equal(shouldAnimateLocation(previous,{...next,event_time:"2026-10-06T00:00:10Z"}),false);
assert.equal(shouldAnimateLocation(previous,{...next,event_time:"2026-10-05T23:59:59Z"}),false);
assert.equal(shouldAnimateLocation(previous,{...next,value:{latitude:37.51,longitude:127.03}}),false);
assert.deepEqual(interpolateCoordinate([0,10],[2,12],.5),[1,11]);
assert.deepEqual(interpolateCoordinate([0,10],[2,12],-1),[0,10]);
assert.deepEqual(interpolateCoordinate([0,10],[2,12],2),[2,12]);
assert.equal(latestObservationAge({observations:{location:previous,speed_mps:next}},Date.parse("2026-10-06T00:00:11Z")),10);
assert.equal(latestObservationAge({observations:{}},Date.now()),Infinity);
console.log("Map interpolation and observation age: passed");
